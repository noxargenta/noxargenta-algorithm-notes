#include <bits/stdc++.h>                    // 引入所有常用 STL
using namespace std;                         // 使用 std 命名空间

using ll = long long;                        // long long 简写


// ============================================================
// 计算某一个特殊 k 的 k-mex
//
// k = mex + s
// s 是原数组中的一个值
//
// vals：排序去重后的数组
// freq：vals 中每个值的出现次数
// cnt：0~n 的出现次数
// ============================================================
int calc(
    ll k,                                     // 当前的 k
    int n,                                    // 数组长度
    int mex,                                  // 原数组 mex
    const vector<ll>& vals,                  // 排序后的不同数字
    const vector<int>& freq,                 // vals 对应的出现次数
    const vector<int>& cnt                   // 0~n 的出现次数
) {
    
    // 因为 k = mex + s
    // 所以 s = k - mex
    ll s = k - mex;


    // --------------------------------------------------------
    // p 指向 <= s 的最大的数
    //
    // 因为 y = s-d
    // 随着 d 增加，y 会越来越小
    // 所以 p 只需要不断向左移动
    // --------------------------------------------------------
    int p = upper_bound(
        vals.begin(),
        vals.end(),
        s
    ) - vals.begin() - 1;


    // --------------------------------------------------------
    // mex 最大只能是 n
    //
    // 所以只需要检查：
    //
    // mex, mex+1, ..., n-1
    // --------------------------------------------------------
    int limit = n - mex;


    // d 表示当前检查的偏移量
    //
    // x = mex + d
    // y = s - d
    //
    // 因为 d 每次 +1
    // 所以 y 每次 -1
    for (int d = 0; d < limit; ++d) {

        // 当前目标数字 x
        int x = mex + d;


        // 当前可以由另一个原数字产生的值
        ll y = s - d;


        // ----------------------------------------------------
        // 将指针 p 向左移动
        //
        // 直到：
        //
        // vals[p] <= y
        //
        // 因为 vals 是排序的
        // 所以整个过程中 p 最多移动 n 次
        // ----------------------------------------------------
        while (p >= 0 && vals[p] > y) {
            --p;
        }


        // ----------------------------------------------------
        // 查询 y 出现次数
        //
        // 如果：
        //
        // vals[p] == y
        //
        // 那么 freq[p] 就是 y 的出现次数
        //
        // 否则 y 不存在
        // ----------------------------------------------------
        int cy = 0;

        if (p >= 0 && vals[p] == y) {
            cy = freq[p];
        }


        // ----------------------------------------------------
        // 查询 x 出现次数
        //
        // 因为 x < n
        // 所以可以直接 O(1) 访问 cnt[x]
        // ----------------------------------------------------
        int cx = cnt[x];


        // ====================================================
        // 情况 1：
        //
        // y < 0
        //
        // y 不可能在原数组中出现
        // 所以 x 只能依靠自己
        // ====================================================
        if (y < 0) {

            // x 不存在
            if (cx == 0) {
                return x;                      // x 成为 mex
            }

            // x 存在
            // 继续检查下一个数字
            continue;
        }


        // ====================================================
        // 情况 2：
        //
        // x == y
        //
        // 说明：
        //
        // 2*x == k
        //
        // 一个 x 自己即可产生 x
        // ====================================================
        if ((ll)x == y) {

            // 如果 x 不存在
            // 那么 x 就无法出现
            if (cx == 0) {
                return x;
            }

            // x 存在
            continue;
        }


        // ====================================================
        // 情况 3：
        //
        // x < y
        //
        // 当前只要求 x 出现
        //
        // x 可以由：
        //
        // x
        //
        // 或：
        //
        // y
        //
        // 产生
        //
        // 所以只要 cnt[x] + cnt[y] >= 1
        // ====================================================
        if ((ll)x < y) {

            // 一个资源都没有
            if (cx + cy == 0) {
                return x;
            }

            // 至少有一个资源
            continue;
        }


        // ====================================================
        // 情况 4：
        //
        // x > y
        //
        // 这时候 x 和 y 都已经属于 mex 前缀
        //
        // 所以两个数字都必须出现
        //
        // 因此需要至少两个资源
        // ====================================================
        else {

            // 只有 0 或 1 个资源
            // 无法同时制造 x 和 y
            if (cx + cy < 2) {
                return x;
            }

            // 至少两个资源
            continue;
        }
    }


    // --------------------------------------------------------
    // 0~n-1 全部可以构造
    //
    // 所以最大 mex 就是 n
    // --------------------------------------------------------
    return n;
}


// ============================================================
// solve
// ============================================================
void solve() {

    // --------------------------------------------------------
    // 读入 n
    // --------------------------------------------------------
    int n;
    cin >> n;


    // --------------------------------------------------------
    // 原数组
    // --------------------------------------------------------
    vector<ll> a(n);


    // --------------------------------------------------------
    // cnt[x]：
    //
    // x 在原数组中出现多少次
    //
    // 这里只需要保存 0~n
    // 因为目标 mex 最大只会到 n
    // --------------------------------------------------------
    vector<int> cnt(n + 1, 0);


    // --------------------------------------------------------
    // 读入数组
    // --------------------------------------------------------
    for (int i = 0; i < n; ++i) {

        // 读入 a[i]
        cin >> a[i];


        // 如果 a[i] <= n
        // 那么记录它的出现次数
        if (a[i] <= n) {
            ++cnt[(int)a[i]];
        }
    }


    // ========================================================
    // 求原数组 mex
    // ========================================================

    int mex = 0;


    // --------------------------------------------------------
    // 一直找到第一个没有出现的数
    // --------------------------------------------------------
    while (mex < n && cnt[mex] > 0) {
        ++mex;
    }


    // ========================================================
    // 对原数组排序
    // ========================================================

    sort(a.begin(), a.end());


    // ========================================================
    // 压缩成：
    //
    // vals = 不同的数
    //
    // freq = 对应出现次数
    //
    // 例如：
    //
    // a = [0,0,1,1,1,5]
    //
    // vals = [0,1,5]
    //
    // freq = [2,3,1]
    // ========================================================

    vector<ll> vals;                         // 不同的值
    vector<int> freq;                        // 每个值出现次数


    // --------------------------------------------------------
    // 扫描排序后的数组
    // --------------------------------------------------------
    for (int i = 0; i < n; ) {

        // j 从 i 开始
        int j = i;


        // 找到与 a[i] 相同的连续区间
        while (j < n && a[j] == a[i]) {
            ++j;
        }


        // 保存这个不同的值
        vals.push_back(a[i]);


        // 保存它出现的次数
        freq.push_back(j - i);


        // 跳到下一个不同的值
        i = j;
    }


    // ========================================================
    // ans[i]
    //
    // 表示：
    //
    // k = mex + vals[i]
    //
    // 时的 k-mex
    // ========================================================

    vector<int> ans(vals.size());


    // --------------------------------------------------------
    // 枚举所有可能的特殊 k
    //
    // k = mex + a[i]
    //
    // 不同的 a[i] 最多 n 个
    // --------------------------------------------------------
    for (int i = 0; i < (int)vals.size(); ++i) {

        // 当前特殊 k
        ll k = mex + vals[i];


        // 计算一次
        ans[i] = calc(
            k,
            n,
            mex,
            vals,
            freq,
            cnt
        );
    }


    // ========================================================
    // 处理 q 个查询
    // ========================================================

    int q;
    cin >> q;


    // 最终需要输出所有答案的 XOR
    ll result = 0;


    // --------------------------------------------------------
    // 一个一个处理查询
    // --------------------------------------------------------
    while (q--) {

        // 当前查询的 k
        ll k;
        cin >> k;


        // ----------------------------------------------------
        // 如果 k 不是 mex + a[i]
        //
        // 那么答案一定就是原 mex
        // ----------------------------------------------------

        ll s = k - mex;


        // ----------------------------------------------------
        // 在 vals 中寻找 s
        //
        // 因为：
        //
        // k = mex + s
        //
        // 且只有 s 属于原数组时才是特殊 k
        // ----------------------------------------------------
        auto it = lower_bound(
            vals.begin(),
            vals.end(),
            s
        );


        // ----------------------------------------------------
        // s 不在原数组
        //
        // => k 不是特殊 k
        //
        // => 答案就是 mex
        // ----------------------------------------------------
        if (it == vals.end() || *it != s) {

            result ^= mex;
        }


        // ----------------------------------------------------
        // s 在原数组
        //
        // => k 是特殊 k
        // ----------------------------------------------------
        else {

            // 获得 vals 中的下标
            int id = it - vals.begin();


            // 把这个特殊 k 的答案加入 XOR
            result ^= ans[id];
        }
    }


    // ========================================================
    // 输出最终 XOR
    // ========================================================
    cout << result << '\n';
}


// ============================================================
// main
// ============================================================
int main() {

    // --------------------------------------------------------
    // 加速 cin / cout
    // --------------------------------------------------------
    ios::sync_with_stdio(false);
    cin.tie(nullptr);


    // --------------------------------------------------------
    // 测试组数
    // --------------------------------------------------------
    int T;
    cin >> T;


    // --------------------------------------------------------
    // 处理所有测试
    // --------------------------------------------------------
    while (T--) {
        solve();
    }


    // 程序正常结束
    return 0;
}